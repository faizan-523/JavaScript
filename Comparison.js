// Comparisons
console.log(5 > 23);
console.log(5 < 23);
console.log(5 >= 5);
console.log(5 <= 5);
console.log(5 == "5");

console.log(null > 0);
console.log(null == 0);
console.log(null >= 0);

console.log(undefined == 5);
console.log(undefined > 5);
console.log(undefined < 5);

// === also checks for data type and value both

console.log(23 === "23"); // not equal because of different data types

